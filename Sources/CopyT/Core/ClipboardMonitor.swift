import AppKit
import CryptoKit

/// 轮询 NSPasteboard.changeCount，捕获文本 / 富文本 / 图片 / 文件
@MainActor
final class ClipboardMonitor {
    var onCapture: ((Capture) -> Void)?

    let pasteboard: NSPasteboard
    /// 判断来源应用（测试时可替换）
    var frontmostApp: () -> (name: String?, bundleID: String?) = {
        let app = NSWorkspace.shared.frontmostApplication
        return (app?.localizedName, app?.bundleIdentifier)
    }

    private var timer: Timer?
    private var lastChangeCount: Int

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        self.lastChangeCount = pasteboard.changeCount
    }

    /// 密码管理器等应用会用这些类型标记"不要记录"
    /// 参见 http://nspasteboard.org
    private static let privateTypes: Set<NSPasteboard.PasteboardType> = Set([
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ].map { (raw: String) in NSPasteboard.PasteboardType(rawValue: raw) })

    func start(interval: TimeInterval = 0.5) {
        stop()
        let t = Timer(timeInterval: interval, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        t.tolerance = interval / 4
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// 本应用自己写入剪贴板后调用，避免把它重复记录
    func markOwnWrite() {
        lastChangeCount = pasteboard.changeCount
    }

    /// 检查一次剪贴板（定时器调用；测试中可直接调用）
    func poll() {
        let pb = pasteboard
        let count = pb.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        guard !Preferences.paused else { return }

        let types = Set(pb.types ?? [])
        guard !types.isEmpty, types.isDisjoint(with: Self.privateTypes) else { return }

        let app = frontmostApp()
        if let bid = app.bundleID, Preferences.ignoredBundleIDs.contains(bid) { return }

        if let capture = Self.makeCapture(from: pb, types: types, sourceApp: app.name) {
            onCapture?(capture)
        }
    }

    // MARK: - 解析剪贴板

    static func makeCapture(from pb: NSPasteboard,
                            types: Set<NSPasteboard.PasteboardType>,
                            sourceApp: String?,
                            maxImageBytes: Int = Preferences.maxImageBytes) -> Capture? {
        // 1. 文件（Finder 复制文件时也会带上文件名字符串和图标，所以优先判断）
        if types.contains(.fileURL),
           let urls = pb.readObjects(forClasses: [NSURL.self],
                                     options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let text = urls.map(\.path).joined(separator: "\n")
            return Capture(kind: .file, text: text, data: nil, fileExtension: nil,
                           sourceApp: sourceApp, hash: sha256("file", Data(text.utf8)), byteSize: 0)
        }

        // 2. 文本 / 富文本（Office 等复制文字时也会附带图片预览，所以文本优先于图片）
        if let str = pb.string(forType: .string),
           !str.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let textHash = sha256("text", Data(str.utf8))
            if types.contains(.rtf), let rtf = pb.data(forType: .rtf) {
                return Capture(kind: .richText, text: str, data: rtf, fileExtension: "rtf",
                               sourceApp: sourceApp, hash: textHash, byteSize: rtf.count)
            }
            if types.contains(.html), let html = pb.data(forType: .html) {
                return Capture(kind: .richText, text: str, data: html, fileExtension: "html",
                               sourceApp: sourceApp, hash: textHash, byteSize: html.count)
            }
            return Capture(kind: .text, text: str, data: nil, fileExtension: nil,
                           sourceApp: sourceApp, hash: textHash, byteSize: str.utf8.count)
        }

        // 3. 图片（截图、浏览器"拷贝图像"等）
        if let png = imagePNGData(from: pb, types: types) {
            guard png.count <= maxImageBytes else { return nil }
            return Capture(kind: .image, text: nil, data: png, fileExtension: "png",
                           sourceApp: sourceApp, hash: sha256("image", png), byteSize: png.count)
        }
        return nil
    }

    private static func imagePNGData(from pb: NSPasteboard, types: Set<NSPasteboard.PasteboardType>) -> Data? {
        if types.contains(.png), let data = pb.data(forType: .png) { return data }
        if types.contains(.tiff), let data = pb.data(forType: .tiff),
           let rep = NSBitmapImageRep(data: data) {
            return rep.representation(using: .png, properties: [:])
        }
        let imageTypes = NSImage.imageTypes.map { NSPasteboard.PasteboardType($0) }
        guard !types.isDisjoint(with: imageTypes),
              let image = NSImage(pasteboard: pb),
              let tiff = image.tiffRepresentation,
              let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    static func sha256(_ prefix: String, _ data: Data) -> String {
        var hasher = SHA256()
        hasher.update(data: Data(prefix.utf8))
        hasher.update(data: data)
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }
}

/// 把历史记录写回剪贴板
enum PasteboardWriter {
    @discardableResult
    static func write(_ item: ClipItem, root: URL, to pb: NSPasteboard = .general) -> Bool {
        let dataURL = item.dataPath.map { root.appendingPathComponent($0) }

        switch item.kind {
        case .text:
            pb.clearContents()
            return pb.setString(item.text ?? "", forType: .string)

        case .richText:
            pb.clearContents()
            if let dataURL, let data = try? Data(contentsOf: dataURL) {
                let type: NSPasteboard.PasteboardType = dataURL.pathExtension == "html" ? .html : .rtf
                pb.setData(data, forType: type)
            }
            return pb.setString(item.text ?? "", forType: .string)

        case .image:
            guard let dataURL, let data = try? Data(contentsOf: dataURL) else { return false }
            pb.clearContents()
            pb.setData(data, forType: .png)
            if let tiff = NSImage(data: data)?.tiffRepresentation {
                pb.setData(tiff, forType: .tiff)
            }
            return true

        case .file:
            let urls = item.filePaths.map { URL(fileURLWithPath: $0) as NSURL }
            guard !urls.isEmpty else { return false }
            pb.clearContents()
            return pb.writeObjects(urls)
        }
    }
}
